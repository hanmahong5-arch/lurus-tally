func main() {
	dir := filepath.Join(filepath.Dir(caller()), "..", "testdata", "industries")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		panic(err)
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			panic(err)
		}
	}
	if err := os.WriteFile(filepath.Join(dir, "hardware-alipay-gbk.csv"), mustGBK(hardware), 0o644); err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "burst-wholesale-alipay.csv"), []byte(burstWholesale()), 0o644); err != nil {
		panic(err)
	}
}

func caller() string {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		panic("caller")
	}
	return file
}

func mustGBK(text string) []byte {
	out, _, err := transform.Bytes(simplifiedchinese.GB18030.NewEncoder(), []byte(text))
	if err != nil {
		panic(err)
	}
	return out
}

func burstWholesale() string {
	var b strings.Builder
	b.WriteString("#账号：[2088000001]\n")
	b.WriteString("账务流水号,发生时间,对方账号,收入金额（+元）,支出金额（-元）,商品名称,备注\n")
	base := time.Date(2026, 5, 1, 0, 0, 0, 0, time.UTC)
	for i := 0; i < 2000; i++ {
		when := base.Add(time.Duration(i) * time.Minute).Format("2006-01-02 15:04:05")
		id := fmt.Sprintf("BW%04d", i+1)
		if i%2 == 0 {
			fmt.Fprintf(&b, "%s,%s,批发客户,10.00,0.00,卷纸,货款\n", id, when)
		} else {
			fmt.Fprintf(&b, "%s,%s,原料供应商,0.00,3.50,原料,进货\n", id, when)
		}
	}
	b.WriteString("合计\n")
	return b.String()
}

